import { Router } from 'express';
import { authenticate } from '../../middlewares/auth.js';
import { catchAsync } from '../../shared/utils/catchAsync.js';
import { formatApiResponse } from '../../shared/utils/ApiResponse.js';
import { validationError } from '../../shared/utils/ApiError.js';
import * as v from './validation.js';
import * as service from './service.js';
const router=Router();
const parse=(schema,data)=>{const result=schema.safeParse(data);if(!result.success)throw validationError('Thông tin hoặc bộ lọc không hợp lệ');return result.data;};
const get=(path,action)=>router.get(path,authenticate,catchAsync(async(req,res)=>formatApiResponse(res,{data:await action(req.user,parse(v.listQuery,req.query),req.params)})));
get('/warehouse-overview',user=>service.overview(user));
get('/warehouses',user=>service.options(user,'warehouse_location:read'));
get('/warehouse-catalogue',(user)=>service.warehouseList(user));
get('/warehouse-catalogue/:id',(user,q,params)=>service.warehouseDetail(user,parse(v.oid,params.id)));
get('/warehouse-locations',(user,query)=>service.locations(user,query));
get('/warehouse-locations/:id',(user,q,params)=>service.locationDetail(user,parse(v.oid,params.id)));
router.post('/warehouse-locations',authenticate,catchAsync(async(req,res)=>formatApiResponse(res,{data:await service.saveLocation(req.user,null,parse(v.createBody,req.body))})));
router.patch('/warehouse-locations/:id',authenticate,catchAsync(async(req,res)=>formatApiResponse(res,{data:await service.saveLocation(req.user,parse(v.oid,req.params.id),parse(v.editBody,req.body))})));
router.post('/warehouse-catalogue',authenticate,catchAsync(async(req,res)=>formatApiResponse(res,{data:await service.saveWarehouse(req.user,null,parse(v.warehouseCreateBody,req.body))})));
router.patch('/warehouse-catalogue/:id',authenticate,catchAsync(async(req,res)=>formatApiResponse(res,{data:await service.saveWarehouse(req.user,parse(v.oid,req.params.id),parse(v.warehouseEditBody,req.body))})));
get('/inventory/options',user=>service.options(user,'inventory:read'));
get('/inventory',(user,query)=>service.inventory(user,query));
get('/inventory/:id',(user,q,params)=>service.inventoryDetail(user,parse(v.oid,params.id)));
get('/stock-movements/options',user=>service.options(user,'stock_movement:read'));
get('/stock-movements',(user,query)=>service.movements(user,query));
get('/stock-movements/:id',(user,q,params)=>service.movements(user,q,parse(v.oid,params.id)));
export default router;
